const tr = (s) => {
  if (WORDS[s] !== undefined) return WORDS[s];
  for (const [re, out] of PATTERNS) {
    const m = s.match(re);
    if (m) return out.replace(/\{(\d)\}/g, (_, i) => WORDS[m[i]] ?? m[i] ?? '');
  }
  return null;
};

const CY = /[А-Яа-яЁё]/;
// Текст узла: перевод середины (пробелы по краям и переносы внутри — как были), иначе null.
function translate(v) {
  if (!CY.test(v)) return null;
  const core = v.trim().replace(/\s+/g, ' ');
  const t = tr(core);
  if (t == null) return null;
  return v.match(/^\s*/)[0] + t + v.match(/\s*$/)[0];
}

const ATTRS = ['placeholder', 'title', 'aria-label'];
function apply(n) {
  if (n.nodeType === 3) {
    if (n.nodeValue === n.__udm) return; // наш же перевод
    const t = translate(n.nodeValue);
    n.__ru = n.nodeValue;
    if (t != null) { n.__udm = t; n.nodeValue = t; } else n.__udm = undefined;
    return;
  }
  if (n.nodeType !== 1 || n.tagName === 'SCRIPT' || n.tagName === 'STYLE') return;
  for (const a of ATTRS) {
    const v = n.getAttribute(a);
    if (!v || v === n.__udmAttr?.[a]) continue;
    const t = translate(v);
    if (t == null) continue;
    (n.__ruAttr ||= {})[a] = v;
    (n.__udmAttr ||= {})[a] = t;
    n.setAttribute(a, t);
  }
  for (const c of n.childNodes) apply(c);
}

function restore(n) {
  if (n.nodeType === 3) { if (n.__ru != null && n.nodeValue === n.__udm) n.nodeValue = n.__ru; n.__ru = n.__udm = undefined; return; }
  if (n.nodeType !== 1) return;
  if (n.__ruAttr) { for (const [a, v] of Object.entries(n.__ruAttr)) if (n.getAttribute(a) === n.__udmAttr[a]) n.setAttribute(a, v); n.__ruAttr = n.__udmAttr = undefined; }
  for (const c of n.childNodes) restore(c);
}

const observer = new MutationObserver((ms) => {
  for (const m of ms) {
    if (m.type === 'characterData' || m.type === 'attributes') apply(m.target);
    else for (const n of m.addedNodes) apply(n);
  }
});
const start = () => {
  apply(document.body);
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
};

export function setLang(l) {
  if (!LANGS[l] || l === lang) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch {}
  document.documentElement.lang = l === 'udm' ? 'udm' : 'ru';
  if (l === 'udm') start();
  else { observer.disconnect(); restore(document.body); }
}
export const toggleLang = () => setLang(lang === 'udm' ? 'ru' : 'udm');

if (lang === 'udm') {
  document.documentElement.lang = 'udm';
  if (document.body) start(); else document.addEventListener('DOMContentLoaded', start);
}
